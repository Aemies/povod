// Текст со ссылками вида [название](https://…) — ссылки проверяются, остальное выводится как обычный текст.
export function rich(text) {
  const frag = document.createDocumentFragment();
  const pattern = /\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g;
  let start = 0;
  const value = String(text || '');
  for (const m of value.matchAll(pattern)) {
    frag.append(value.slice(start, m.index));
    const url = safeUrl(m[2]);
    frag.append(url ? h('a', { href: url, target: '_blank', rel: 'noopener noreferrer' }, m[1]) : m[1]);
    start = m.index + m[0].length;
  }
  frag.append(value.slice(start));
  return frag;
}
